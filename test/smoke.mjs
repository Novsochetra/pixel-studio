import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const url = process.argv[2];
const out = process.argv[3];
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, colorScheme: 'dark' });
const errors = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errors.push(`${m.type()}: ${m.text()}`); });
page.on('pageerror', (e) => errors.push(`pageerror: ${e.message}`));
await page.addInitScript(() => localStorage.setItem('pixel-clean-quick-start', '1'));
await page.goto(url);
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/01-edit.png` });
// draw a stroke
const canvas = page.getByLabel('Pixel canvas');
const box = await canvas.boundingBox();
await page.mouse.move(box.x + 20, box.y + 20); await page.mouse.down(); await page.mouse.move(box.x + 120, box.y + 60, { steps: 10 }); await page.mouse.up();
await page.waitForTimeout(300);
await page.keyboard.press('Meta+z');
await page.waitForTimeout(300);
// board
await page.getByRole('button', { name: 'Views board' }).click();
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/02-board.png` });
await page.getByRole('button', { name: 'On the pitch' }).click();
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/03-game.png` });
await page.getByRole('button', { name: 'Edit', exact: true }).click();
// import back2 via drop on stage after selecting Back
await page.locator('.view-row', { hasText: 'Back' }).click();
const buffer = (await import('node:fs')).readFileSync(process.argv[4]);
const dataTransfer = await page.evaluateHandle((bytes) => { const dt = new DataTransfer(); dt.items.add(new File([new Uint8Array(bytes)], 'back2.webp', { type: 'image/webp' })); return dt; }, [...buffer]);
await page.dispatchEvent('#stage', 'drop', { dataTransfer });
await page.waitForSelector('text=Grid:', { timeout: 20000 }).catch(() => errors.push('no report'));
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/04-import.png` });
const report = await page.locator('pre.report').textContent().catch(() => 'none');
console.log('REPORT', report);
await page.getByRole('button', { name: /Use for Back/ }).click();
await page.waitForTimeout(300);
// swap colours
await page.getByRole('button', { name: 'Swap colours…' }).click();
await page.waitForTimeout(300);
await page.getByRole('button', { name: 'Make an 8-colour palette from the character' }).click();
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/05-swap.png` });
await page.keyboard.press('Escape');
await page.getByRole('button', { name: 'Download' }).click();
await page.waitForTimeout(200);
await page.screenshot({ path: `${out}/06-menu.png` });
const [download] = await Promise.all([page.waitForEvent('download', { timeout: 5000 }).catch(() => null), page.getByRole('menuitem', { name: /All views/ }).click()]);
console.log('DOWNLOAD', download ? download.suggestedFilename() : 'none');
await page.waitForTimeout(2500);
console.log('SAVE', await page.locator('.save-status').textContent());
console.log('ERRORS', JSON.stringify(errors, null, 1));
await browser.close();
